#!/usr/bin/env bash
# Install agent-kit for the current user on Linux or macOS. Idempotent; rerun after pulling.
#   - links every skills/<name> into ~/.claude/skills (Claude Code) and ~/.agents/skills (Codex and others)
#   - writes ~/.claude/CLAUDE.md: imports global/AGENTS.md, plus ~/.agents/personal.md if present
#   - writes ~/.codex/AGENTS.md: the same two files concatenated (Codex has no imports), if ~/.codex exists
set -euo pipefail
kit="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
personal="$HOME/.agents/personal.md"

sync_skills() {
  local dest="$1" link name n=0
  mkdir -p "$dest"
  # drop links into this kit whose skill is gone; other links and real dirs are left alone
  for link in "$dest"/*; do
    [[ -L "$link" ]] || continue
    if [[ "$(readlink "$link")" == "$kit/"* && ! -f "$(readlink "$link")/SKILL.md" ]]; then
      rm "$link"; echo "unlinked: $link"
    fi
  done
  for src in "$kit"/skills/*/; do
    src="${src%/}"; name="$(basename "$src")"
    [[ -f "$src/SKILL.md" ]] || continue
    link="$dest/$name"
    if [[ -e "$link" && ! -L "$link" ]]; then echo "skip: $link is a real dir"; continue; fi
    ln -sfn "$src" "$link"; n=$((n + 1))
  done
  echo "linked $n skills into $dest"
}

sync_skills "$HOME/.claude/skills"
sync_skills "$HOME/.agents/skills"

rules="$kit/global/AGENTS.md"
{ echo "@$rules"; if [[ -f "$personal" ]]; then echo "@~/.agents/personal.md"; fi; } > "$HOME/.claude/CLAUDE.md"
echo "wrote: ~/.claude/CLAUDE.md"

codex_home="${CODEX_HOME:-$HOME/.codex}"
if [[ -d "$codex_home" ]]; then
  { echo "<!-- Generated by agent-kit install.sh from $rules; edit the sources, then rerun. -->"; echo
    cat "$rules"; if [[ -f "$personal" ]]; then echo; cat "$personal"; fi; } > "$codex_home/AGENTS.md"
  echo "wrote: $codex_home/AGENTS.md"
fi
