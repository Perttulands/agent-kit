# Install agent-kit for the current user on Windows. Idempotent; rerun after pulling.
# Usage: powershell -ExecutionPolicy Bypass -File install.ps1
#   - links every skills\<name> into ~\.claude\skills (Claude Code) and ~\.agents\skills (Codex and others)
#   - writes ~\.claude\CLAUDE.md: imports global\AGENTS.md, plus ~\.agents\personal.md if present
#   - writes ~\.codex\AGENTS.md: the same two files concatenated (Codex has no imports)
$ErrorActionPreference = 'Stop'
$kit = $PSScriptRoot
$personal = Join-Path $HOME '.agents\personal.md'

function Sync-Skills([string]$dest) {
  New-Item -ItemType Directory -Force $dest | Out-Null
  $wanted = @{}
  Get-ChildItem (Join-Path $kit 'skills') -Directory | Where-Object { Test-Path (Join-Path $_.FullName 'SKILL.md') } |
    ForEach-Object { $wanted[$_.Name] = $_.FullName }
  # drop links into this kit whose skill is gone; other links and real dirs are left alone
  Get-ChildItem $dest -Directory | Where-Object { $_.LinkType -and "$($_.Target)".StartsWith($kit) -and -not $wanted.ContainsKey($_.Name) } |
    ForEach-Object { cmd /c rmdir "$($_.FullName)" | Out-Null; "unlinked: $($_.FullName)" }
  foreach ($name in $wanted.Keys) {
    $link = Join-Path $dest $name
    $item = Get-Item $link -ErrorAction SilentlyContinue
    if ($item -and -not $item.LinkType) { "skip: $link is a real dir"; continue }
    if ($item) { cmd /c rmdir "$link" | Out-Null }
    cmd /c mklink /J "$link" "$($wanted[$name])" | Out-Null
  }
  "linked $($wanted.Count) skills into $dest"
}

Sync-Skills (Join-Path $HOME '.claude\skills')
Sync-Skills (Join-Path $HOME '.agents\skills')

$rules = Join-Path $kit 'global\AGENTS.md'
$claudeMd = "@$($rules.Replace('\','/'))`n"
if (Test-Path $personal) { $claudeMd += "@~/.agents/personal.md`n" }
New-Item -ItemType Directory -Force (Join-Path $HOME '.claude') | Out-Null
[IO.File]::WriteAllText((Join-Path $HOME '.claude\CLAUDE.md'), $claudeMd)
"wrote: ~\.claude\CLAUDE.md"

$codexHome = if ($env:CODEX_HOME) { $env:CODEX_HOME } else { Join-Path $HOME '.codex' }
if (Test-Path $codexHome) {
  $text = "<!-- Generated by agent-kit install.ps1 from $rules; edit the sources, then rerun. -->`n`n" + [IO.File]::ReadAllText($rules)
  if (Test-Path $personal) { $text += "`n" + [IO.File]::ReadAllText($personal) }
  [IO.File]::WriteAllText((Join-Path $codexHome 'AGENTS.md'), $text)
  "wrote: $codexHome\AGENTS.md"
}
